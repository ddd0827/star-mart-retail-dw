SELECT
    dt,
    dt_date,
    location_id,
    sk_location,
    location_name,
    store_type,
    city_id,
    region_id,
    is_offline,
    product_id,
    sk_product,
    product_name,
    category_id,
    category_name,
    top_category_id,
    top_category_name,
    begin_qty,
    purchase_in_qty,
    sale_qty,
    return_qty,
    adjustment_qty,
    end_qty,
    safety_stock,
    cost_price,
    stock_value,
    stock_status,
    CASE WHEN end_qty = 0 THEN 1 ELSE 0 END AS is_stockout,
    CAST(begin_qty + purchase_in_qty AS INT) AS available_qty,
    ROUND(sale_qty / NULLIF(begin_qty + purchase_in_qty, 0), 4) AS sell_through_rate,
    CASE WHEN sale_qty > 0 THEN ROUND(end_qty / sale_qty, 2) ELSE NULL END AS days_of_supply,
    CURRENT_TIMESTAMP() AS etl_time
FROM dwd_inventory_snapshot
